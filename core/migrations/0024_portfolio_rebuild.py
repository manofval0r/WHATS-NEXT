"""
Portfolio rebuild: schema corrections and the data repairs they require.

Hand-written rather than autogenerated because three operations need data
steps Django cannot infer:

* ``UserRoadmapItem.created_at`` is added as nullable, backfilled from the
  existing ``submitted_at``, then promoted to ``auto_now_add``. Autogenerated,
  it emits ``default=None`` against a populated table and fails.
* The new ``UniqueConstraint(user, step_order)`` requires de-duplicating
  first. Concurrent roadmap generation could previously interleave deletes
  and inserts and leave two modules claiming the same position.
* ``UserActivity.count`` may hold the old 1000-sentinel used to mark the
  daily quiz. That value was being summed as 1000 real contributions, so it
  has to move into its own column and be subtracted back out.

Also removes the employer side and adds the XP ledger and skill-transfer
models.
"""


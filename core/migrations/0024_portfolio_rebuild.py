def backfill_created_at(apps, schema_editor):
    """created_at <- submitted_at (the only timestamp existing rows had)."""
    Item = apps.get_model("core", "UserRoadmapItem")
    Item.objects.filter(created_at__isnull=True).update(
        created_at=django.utils.timezone.now()
    )


def deduplicate_step_order(apps, schema_editor):
    """
    Renumber each user's modules to a dense 0..n-1 sequence.

    Walks in id order so the result is deterministic. Completing modules
    keep their relative position; only the numbering changes.
    """
    Item = apps.get_model("core", "UserRoadmapItem")

    user_ids = (
        Item.objects.values_list("user_id", flat=True).distinct().order_by("user_id")
    )

    for user_id in user_ids.iterator():
        seen = 0
        for pk in (
            Item.objects.filter(user_id=user_id)
            .order_by("step_order", "id")
            .values_list("id", flat=True)
        ):
            # Move to a safe offset first: the unique constraint does not
            # exist yet, but the intermediate states must stay sane.
            Item.objects.filter(pk=pk).update(step_order=seen + 100000)
            Item.objects.filter(pk=pk).update(step_order=seen)
            seen += 1


def migrate_daily_quiz_sentinel(apps, schema_editor):
    """
    Move the 1000-sentinel out of the real activity counter.

    The daily quiz used to write ``count = 1000`` to mark completion. Every
    consumer summed ``count`` as if it were real activity, so one quiz click
    awarded 15,000 XP and lit the heatmap. The sentinel becomes a timestamp;
    the count drops to a sane value (anything at or above the sentinel was
    never a real count).
    """
    Activity = apps.get_model("core", "UserActivity")

    for activity in Activity.objects.filter(count__gte=1000).iterator():
        # activity.date is a Date; the target column is a DateTimeField and
        # USE_TZ is on, so anchor it to midnight in the current timezone
        # rather than assigning a naive value.
        activity.daily_quiz_completed_at = django.utils.timezone.make_aware(
            datetime.datetime.combine(activity.date, datetime.time.min),
            django.utils.timezone.get_current_timezone(),
        )
        activity.count = 3
        activity.save(update_fields=["daily_quiz_completed_at", "count"])


def seed_xp_from_existing(apps, schema_editor):
    """
    Open a balance for users who already have activity, so the new ledger
    does not start everyone at zero relative to the profile they can see.
    """
    User = apps.get_model("core", "User")
    XpEvent = apps.get_model("core", "XpEvent")

    for user in User.objects.all().iterator():
        XpEvent.objects.get_or_create(
            user_id=user.pk,
            reason="adjustment",
            reference="migration-0024",
            defaults={
                "amount": 0,
                "scope": "learning",
            },
        )


